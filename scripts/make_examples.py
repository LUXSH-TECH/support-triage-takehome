"""Regenerate docs/EXAMPLES.md from live calls (fake provider). python -m scripts.make_examples"""
import json
import tempfile
from dataclasses import replace
from pathlib import Path

from fastapi.testclient import TestClient

from app.config import Settings
from app.main import create_app

EXAMPLES = [
    ("Northstar return, 20 days, eligible", "test-key-northstar-001",
     {"ticket_id": "T-1001", "order_ref": "NS-88231", "message": "The jacket doesn't fit, I'd like to send it back.", "facts": {"unused": True}}),
    ("Cedar return, same facts, window passed", "test-key-cedar-002",
     {"ticket_id": "T-1002", "order_ref": "CD-40012", "message": "The jacket doesn't fit, I'd like to send it back."}),
    ("Client says unused / not final sale, ERP says final sale", "test-key-northstar-001",
     {"ticket_id": "T-1003", "order_ref": "NS-88260", "message": "I'd like to return this, it is unused.", "facts": {"unused": True, "final_sale": False}}),
    ("ERP timeout -> bounded fallback", "test-key-northstar-001",
     {"ticket_id": "T-1004", "order_ref": "NS-88231-TIMEOUT", "message": "I want to return my jacket."}),
]

tmp = tempfile.mkdtemp()
s = replace(Settings(), database_url=f"sqlite:///{tmp}/ex.db")
out = ["# Example requests and responses", "",
       "Generated by `python -m scripts.make_examples` against the local service with the **fake** model provider.", ""]
with TestClient(create_app(s)) as c:
    for title, key, body in EXAMPLES:
        r = c.post("/triage", headers={"X-API-Key": key}, json=body)
        d = r.json(); d["request_id"] = "<uuid>"; d["latency_ms"] = "<ms>"
        retailer = "northstar" if "northstar" in key else "cedar"
        out += [f"## {title}", "", "```bash",
                f"curl -s localhost:8000/triage -H 'X-API-Key: test-key-{retailer}-00{1 if retailer=='northstar' else 2}' -H 'Content-Type: application/json' \\",
                "  -d '" + json.dumps(body).replace("'", "'\\''") + "'", "```", "", f"HTTP {r.status_code}", "", "```json", json.dumps(d, indent=2), "```", ""]
    r = c.post("/triage", json=EXAMPLES[0][2])
    out += ["## Missing API key", "", f"HTTP {r.status_code} `{r.text}`", ""]
    r = c.post("/triage", headers={"X-API-Key": "test-key-northstar-001"}, json={**EXAMPLES[0][2], "facts": {"days_since_delivery": -1}})
    out += ["## Negative day count", "", f"HTTP {r.status_code}", ""]
    out += ["## Health", "", "```json", json.dumps(c.get("/health").json(), indent=2), "```", ""]
Path("docs/EXAMPLES.md").write_text("\n".join(out))
print("wrote docs/EXAMPLES.md")
